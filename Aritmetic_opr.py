# --------------------
# [+] Addition
# [-] Subtraction
# [*] Multiplication
# [/] Division
# [%] Modulus
# [ ** ] Exponent
# [//] Floor Division
#---------------------
# [+] Addition
print (10+30)
print (10 + -30)
print(1+2.66)
# [-] Subtraction
print (60 - 30)
print( -30 - -30)
# [*] Multiplication
print (10*3)
print((5+10)*100)
# [/] Division
print (int(100/20))
# [%] Modulus
print (8%2) # 0
print (9%2)
print (20%5)
print (22%5)
# [ ** ] Exponent
print (2**5)
print (5**4)
# [//] Floor Division
print (100//22)